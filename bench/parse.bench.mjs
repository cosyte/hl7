// Benchmarks for @cosyte/hl7, on @cosyte/bench, against the built entry a consumer imports.
//
// A reading of this build (throughput, latency p50/p95/p99, allocations, peak heap, a long run for
// leaks, and the cold import with every file it loads and its gzip size):
//   pnpm build && pnpm bench:reading --out bench-results/reading.json
// A base against head comparison, the base built in another checkout:
//   pnpm bench:compare --base <base checkout>/dist/index.mjs --head dist/index.mjs
// On a pull request CI runs that comparison in its bench-compare job, over the sizes marked
// compared below, and the bench-reading workflow's large-compare job runs the same comparison over
// the large sizes, from bench/parse-large.compare.mjs. Both are advisory: they post their numbers
// and fail nothing until a calibration on their runner class shows false alarms under 1%.
//
// The suite is handed the module under test rather than importing it, so one file measures both
// builds. Every message is synthetic and built here from an index: no file is read, and every name,
// identifier and value is made up.

import { defineBenchmark, defineSuite } from "@cosyte/bench";

const KIB = 1024;

/** One synthetic OBX result line. */
function obx(k) {
  return `OBX|${String(k + 1)}|NM|GLU^Glucose^LN||${String(80 + (k % 40))}|mg/dL|70-110|N|||F|||20260101120000`;
}

/** A synthetic ADT^A01 of five segments, 280 bytes: the most common message there is. */
export function adtMessage(i) {
  const id = String(i).padStart(6, "0");
  return (
    `MSH|^~\\&|SENDAPP|SENDFAC|RECVAPP|RECVFAC|20260101120000||ADT^A01|A${id}|P|2.5\r` +
    `EVN|A01|20260101120000\r` +
    `PID|1||FAKE${id}^^^HOSP^MR||Doe^Jane^Q||19800101|F|||123 Main St^^Anytown^CA^90001\r` +
    `NK1|1|Doe^John^R|SPO|123 Main St^^Anytown^CA^90001\r` +
    `PV1|1|I|WARD^101^A|||||DOC123^Smith^Robert\r`
  );
}

/** A synthetic ORU^R01 of about `bytes` bytes: a header, a patient, an order, then results. */
export function oruMessage(i, bytes) {
  const id = String(i).padStart(6, "0");
  let text =
    `MSH|^~\\&|LAB|SENDFAC|EHR|RECVFAC|20260101120000||ORU^R01|R${id}|P|2.5\r` +
    `PID|1||FAKE${id}^^^HOSP^MR||Roe^Sam^T||19750615|M\r` +
    `OBR|1||ACC${id}|CBC^Complete Blood Count^LN|||20260101120000\r`;
  const lines = [];
  for (let k = 0, n = text.length; n < bytes; k++) {
    const line = obx(k);
    lines.push(line);
    n += line.length + 1;
  }
  text += `${lines.join("\r")}\r`;
  return text;
}

/**
 * `bytes` generated bytes, base64: a stand-in for an embedded document. A fixed linear
 * congruential sequence, so every run builds the same bytes and no file is read.
 */
function base64Document(bytes, seed) {
  const data = Buffer.alloc(bytes);
  let state = (seed * 2654435761 + 1) >>> 0;
  for (let k = 0; k < bytes; k++) {
    state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
    data[k] = state >>> 24;
  }
  return data.toString("base64");
}

/**
 * A synthetic ORU^R01 of about `bytes` bytes that carries one document: a header, a patient, an
 * order, a short note, then one OBX of value type ED whose fifth component is the document, in
 * base64. This is how a real message usually reaches a MiB: one large field, not many lines.
 */
export function documentMessage(i, bytes) {
  const id = String(i).padStart(6, "0");
  const head =
    `MSH|^~\\&|LAB|SENDFAC|EHR|RECVFAC|20260101120000||ORU^R01|D${id}|P|2.5\r` +
    `PID|1||FAKE${id}^^^HOSP^MR||Roe^Sam^T||19750615|M\r` +
    `OBR|1||ACC${id}|11502-2^Laboratory report^LN|||20260101120000\r` +
    `OBX|1|TX|11502-2^Laboratory report^LN||Report attached||||||F\r`;
  const prefix = `OBX|2|ED|11502-2^Laboratory report^LN||^AP^PDF^Base64^`;
  const suffix = `||||||F|||20260101120000\r`;
  // Base64 writes four characters for every three bytes; rounding up keeps the message at least
  // `bytes` long, and at most three bytes over.
  const room = bytes - head.length - prefix.length - suffix.length;
  const documentBytes = Math.max(3, Math.ceil(room / 4) * 3);
  return head + prefix + base64Document(documentBytes, i) + suffix;
}

